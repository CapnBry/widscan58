#!/usr/bin/env python3
"""Generate firmware/src/dsp/fft_twiddle_q15.h: W_N^k = exp(-2j*pi*k/N) in Q15
for the portable radix-4 FFT (psd.c). GPL-3.0-or-later.

  tools/gen_twiddle.py > firmware/src/dsp/fft_twiddle_q15.h
"""
import math

N = 1024  # largest size the table serves; smaller sizes stride through it
K = 3 * N // 4  # radix-4 needs W^j, W^2j, W^3j with j < N/4
vals = []
for k in range(K):
    a = -2 * math.pi * k / N
    vals += [round(32767 * math.cos(a)), round(32767 * math.sin(a))]
print("/* Generated by tools/gen_twiddle.py; do not edit. GPL-3.0-or-later.")
print(f" * W_{N}^k = exp(-2*pi*i*k/{N}) in Q15 (x32767), k = 0..{K - 1}: re, im pairs. */")
print("#pragma once")
print("#include <stdint.h>")
print(f"#define FFT_TWIDDLE_N {N}")
print(f"static const int16_t fft_twiddle_q15[{2 * K}] = {{")
for i in range(0, len(vals), 12):
    print("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
print("};")
